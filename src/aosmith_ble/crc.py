def crc8(data: bytes) -> int:
    """CRC over ``data``; append the result to form a complete frame."""
    crc = 0
    for byte in data:
        crc = CRC_TABLE[crc ^ byte]
    return crc


def frame(body: bytes) -> bytes:
    """Append the CRC to a frame body."""
    return body + bytes([crc8(body)])


def check(frame_bytes: bytes) -> bool:
    """True if the trailing CRC of a complete frame is correct."""
    return len(frame_bytes) >= 2 and crc8(frame_bytes[:-1]) == frame_bytes[-1]
